import {Suspense} from 'react';
import {Await, NavLink} from 'react-router';
import type {FooterQuery, HeaderQuery} from 'storefrontapi.generated';

interface FooterProps {
  footer: Promise<FooterQuery | null>;
  header: HeaderQuery;
  publicStoreDomain: string;
}

export function Footer({
  footer: footerPromise,
  header,
  publicStoreDomain,
}: FooterProps) {
  return (
    <Suspense>
      <Await resolve={footerPromise}>
        {(footer) => (
          <footer className="footer">
            <div className="footer-top">
              <div className="footer-brand">
                <p className="wordmark">
                  <span className="wordmark-name">NEXTBODY</span>
                  <span className="wordmark-pip" aria-hidden="true" />
                </p>
                <p className="footer-tag">The screenless band. The body, read.</p>
              </div>
              <nav className="footer-col" aria-label="Product">
                <p className="footer-label">Product</p>
                <a href="/#band">The Band</a>
                <NavLink prefetch="intent" to="/collections/all">
                  Shop
                </NavLink>
                <a href="/#science">Science</a>
              </nav>
              <FooterMenu
                menu={footer?.menu}
                primaryDomainUrl={header.shop.primaryDomain.url}
                publicStoreDomain={publicStoreDomain}
              />
            </div>
            <div className="footer-bottom">
              <p>18+. Not a medical device. No ECG.</p>
              <p>© 2026 NextBody</p>
            </div>
          </footer>
        )}
      </Await>
    </Suspense>
  );
}

function FooterMenu({
  menu,
  primaryDomainUrl,
  publicStoreDomain,
}: {
  menu: FooterQuery['menu'];
  primaryDomainUrl: FooterProps['header']['shop']['primaryDomain']['url'];
  publicStoreDomain: string;
}) {
  return (
    <nav className="footer-col" aria-label="Legal">
      <p className="footer-label">Legal</p>
      {(menu || FALLBACK_FOOTER_MENU).items.map((item) => {
        if (!item.url) return null;
        const url =
          item.url.includes('myshopify.com') ||
          item.url.includes(publicStoreDomain) ||
          item.url.includes(primaryDomainUrl)
            ? new URL(item.url).pathname
            : item.url;
        const isExternal = !url.startsWith('/');
        return isExternal ? (
          <a href={url} key={item.id} rel="noopener noreferrer" target="_blank">
            {item.title}
          </a>
        ) : (
          <NavLink
            className={({isActive, isPending}) =>
              isPending ? 'is-pending' : isActive ? 'is-active' : undefined
            }
            end
            key={item.id}
            prefetch="intent"
            to={url}
          >
            {item.title}
          </NavLink>
        );
      })}
    </nav>
  );
}

